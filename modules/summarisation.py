"""Clinical history summary.

The summary is produced by a RULE-BASED engine: plain Python that turns structured records into
sentences. No AI model is used and nothing leaves the computer. Each statement carries the identifiers
of the records it was built from, so the UI can show the source behind every sentence.

The `SummaryEngine` interface lets a future iteration plug in an AI summariser (see
`ExternalModelEngine`, a documented placeholder that is intentionally not connected to anything).
"""
from __future__ import annotations

from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from datetime import date

import pandas as pd
import streamlit as st

from modules import analytics, data_quality
from modules.dashboard import recent_events
from utils import ui
from utils.data_processing import (age_from_dob, build_records, fmt_date, fmt_num, is_missing, patient_name,
                                   ref_range_str)


@dataclass
class Statement:
    text: str
    sources: list[str] = field(default_factory=list)
    kind: str = "fact"          # fact | missing | note


@dataclass
class Section:
    key: str
    title: str
    statements: list[Statement] = field(default_factory=list)

    @property
    def source_ids(self) -> list[str]:
        seen: dict[str, None] = {}
        for s in self.statements:
            for i in s.sources:
                seen[i] = None
        return list(seen)


@dataclass
class Summary:
    patient_id: str
    engine: str
    as_of: date
    sections: list[Section]

    def to_text(self) -> str:
        lines = [f"CAREFLOW CLINICAL HISTORY SUMMARY - patient {self.patient_id}",
                 "SYNTHETIC DATA. System-generated by the " + self.engine + " as of " + self.as_of.isoformat() + ". Not verified clinical documentation.", ""]
        for s in self.sections:
            lines.append(s.title.upper())
            for st_ in s.statements:
                tag = {"missing": "[Not recorded] ", "note": "[Note] "}.get(st_.kind, "")
                ref = f" (sources: {', '.join(st_.sources)})" if st_.sources else ""
                lines.append(f"- {tag}{st_.text}{ref}")
            lines.append("")
        return "\n".join(lines)


class SummaryEngine(ABC):
    name = "abstract engine"

    @abstractmethod
    def generate(self, bundle: dict[str, pd.DataFrame], as_of: date | None = None) -> Summary: ...


class ExternalModelEngine(SummaryEngine):
    """Placeholder showing where an AI summariser could be added in future. NOT connected to anything.

    A future implementation would need: a privacy review, a source-citation contract (every sentence must
    cite record ids), and evaluation against the rule-based output. It is intentionally not selectable in the UI."""
    name = "external AI model (not implemented)"

    def generate(self, bundle, as_of=None) -> Summary:  # pragma: no cover
        raise NotImplementedError("No AI model is connected in this prototype.")


# ---- helpers ------------------------------------------------------------------------------------------
def dates_phrase(dates: list) -> str:
    ds = sorted(pd.to_datetime(pd.Series(dates).dropna()).unique())
    if not ds:
        return "no dates recorded"
    labels = [fmt_date(d, "%d %b %Y") for d in ds]
    if len(labels) <= 6:
        return ", ".join(labels[:-1]) + (" and " if len(labels) > 1 else "") + labels[-1]
    return f"{len(labels)} dates between {labels[0]} and {labels[-1]}"


def med_text(m) -> str:
    parts = [str(m[k]) for k in ("dose", "route", "frequency") if not is_missing(m[k])]
    return f"{m['name']} {' '.join(parts)}" if parts else f"{m['name']} (dose details not recorded)"


class RuleBasedSummaryEngine(SummaryEngine):
    name = "rule-based summary engine (no AI model)"

    def generate(self, bundle: dict[str, pd.DataFrame], as_of: date | None = None) -> Summary:
        as_of = as_of or date.today()
        records = build_records(bundle)
        findings = data_quality.audit(bundle, as_of, include_mapping=False)
        pid = bundle["patients"].iloc[0]["patient_id"]
        secs = [self._overview(bundle, as_of), self._history(bundle), self._encounters(bundle), self._diagnoses(bundle),
                self._medications(bundle), self._observations(bundle), self._procedures(bundle),
                self._recent(records, bundle), self._followup(bundle, as_of), self._missing(bundle, findings)]
        return Summary(pid, self.name, as_of, secs)

    # 1
    def _overview(self, b, as_of) -> Section:
        p = b["patients"].iloc[0]
        s = Section("overview", "1. Patient overview")
        age = age_from_dob(p["birth_date"], as_of)
        who = f"{patient_name(p)} (synthetic patient {p['patient_id']}), {p['sex'] or 'sex not recorded'}"
        who += f", born {fmt_date(p['birth_date'])} (age {age})." if age is not None else ", date of birth not recorded."
        s.statements.append(Statement(who, [p["patient_id"]]))
        enc = b["encounters"]
        dated = enc.dropna(subset=["start_date"])
        if len(enc):
            span = f" between {fmt_date(dated['start_date'].min())} and {fmt_date(dated['start_date'].max())}" if not dated.empty else ""
            s.statements.append(Statement(f"{len(enc)} encounter(s) are recorded{span}.", list(enc["encounter_id"])))
        else:
            s.statements.append(Statement("No encounters are recorded.", [], "missing"))
        s.statements.append(Statement(
            f"The record contains {len(b['conditions'])} condition record(s), {len(b['medications'])} medication record(s), "
            f"{len(b['observations'])} observation record(s), {len(b['procedures'])} procedure record(s) and {len(b['documents'])} document(s).", []))
        return s

    # 2
    def _history(self, b) -> Section:
        s = Section("history", "2. Recorded medical history")
        c, enc = b["conditions"], b["encounters"]
        first = pd.to_datetime(enc["start_date"].dropna()).min() if not enc["start_date"].dropna().empty else None
        n = 0
        for _, r in c.iterrows():
            onset = pd.to_datetime(r["onset_date"]) if not is_missing(r["onset_date"]) else None
            earlier = first is not None and onset is not None and onset < first
            if earlier or r["clinical_status"] in ("resolved", "inactive"):
                txt = f"{r['display']}: onset recorded {fmt_date(onset)}" if onset is not None else f"{r['display']}: onset date not recorded"
                txt += f"; status '{r['clinical_status']}'."
                if r["verification_status"] not in ("confirmed", None):
                    txt += f" Verification status recorded as '{r['verification_status']}'."
                s.statements.append(Statement(txt, [r["condition_id"]]))
                n += 1
        if n == 0:
            s.statements.append(Statement("No conditions with an onset before the first documented encounter, and no resolved or inactive conditions, are recorded.", [], "missing"))
        return s

    # 3
    def _encounters(self, b) -> Section:
        s = Section("encounters", "3. Relevant encounter history")
        enc = b["encounters"].copy()
        if enc.empty:
            s.statements.append(Statement("No encounters are recorded.", [], "missing"))
            return s
        mix = enc["enc_class"].value_counts().to_dict()
        s.statements.append(Statement("Encounter types recorded: " + ", ".join(f"{v} {k}" for k, v in mix.items()) + ".", list(enc["encounter_id"])))
        for _, e in enc[enc["enc_class"] == "inpatient"].sort_values("start_date").iterrows():
            txt = f"Inpatient admission {fmt_date(e['start_date'])} to {fmt_date(e['end_date'])}: {e['reason']} ({e['department']})."
            if not is_missing(e["disposition"]):
                txt += f" Disposition recorded: {e['disposition']}."
            src = [e["encounter_id"]] + ([e["source_doc_id"]] if not is_missing(e["source_doc_id"]) else [])
            s.statements.append(Statement(txt, src))
        dated = enc.dropna(subset=["start_date"])
        if not dated.empty:
            last = dated.sort_values("start_date").iloc[-1]
            reason = last["reason"] if not is_missing(last["reason"]) else "reason not recorded"
            s.statements.append(Statement(f"Most recent dated encounter: {fmt_date(last['start_date'])}, {last['enc_class']}, {reason}.", [last["encounter_id"]]))
        und = enc[enc["start_date"].isna()]
        if len(und):
            s.statements.append(Statement(f"{len(und)} encounter(s) have no recorded date and cannot be placed in the sequence.", list(und["encounter_id"]), "missing"))
        return s

    # 4
    def _diagnoses(self, b) -> Section:
        s = Section("diagnoses", "4. Recorded diagnoses and conditions")
        c = b["conditions"]
        if c.empty:
            s.statements.append(Statement("No diagnoses or conditions are recorded.", [], "missing"))
            return s
        for status, grp in c.groupby(c["clinical_status"].fillna("status not recorded")):
            names = []
            for _, r in grp.iterrows():
                tag = "" if r["verification_status"] in ("confirmed", None) else f" ({r['verification_status']})"
                names.append(r["display"] + tag)
            s.statements.append(Statement(f"Status '{status}': " + "; ".join(names) + ".", list(grp["condition_id"])))
        return s

    # 5
    def _medications(self, b) -> Section:
        s = Section("medications", "5. Medication history")
        m = b["medications"]
        if m.empty:
            s.statements.append(Statement("No medication records are present.", [], "missing"))
            return s
        act = m[m["status"] == "active"]
        if len(act):
            items = [f"{med_text(r)}" + (f" (since {fmt_date(r['start_date'])})" if not is_missing(r["start_date"]) else " (start date not recorded)") for _, r in act.iterrows()]
            s.statements.append(Statement(f"{len(act)} medication record(s) have status 'active': " + "; ".join(items) + ".", list(act["medication_id"])))
        else:
            s.statements.append(Statement("No medication records have status 'active'.", [], "note"))
        for status in ("completed", "stopped"):
            g = m[m["status"] == status]
            if len(g):
                items = []
                for _, r in g.iterrows():
                    d = f"{fmt_date(r['start_date'])} to {fmt_date(r['end_date'])}" if not is_missing(r["end_date"]) else f"started {fmt_date(r['start_date'])}, end date not recorded"
                    items.append(f"{med_text(r)} ({d})")
                s.statements.append(Statement(f"{len(g)} record(s) with status '{status}': " + "; ".join(items) + ".", list(g["medication_id"])))
        other = m[~m["status"].isin(["active", "completed", "stopped"])]
        if len(other):
            s.statements.append(Statement(f"{len(other)} medication record(s) have no recognised status.", list(other["medication_id"]), "missing"))
        inc = m[m[["dose", "route", "frequency"]].isna().any(axis=1)]
        if len(inc):
            s.statements.append(Statement("Dose, route or frequency is not recorded for: " + ", ".join(f"{r['name']} ({r['medication_id']})" for _, r in inc.iterrows()) + ".",
                                          list(inc["medication_id"]), "missing"))
        return s

    # 6
    def _observations(self, b) -> Section:
        s = Section("observations", "6. Laboratory and observation history")
        obs = b["observations"]
        if obs.empty:
            s.statements.append(Statement("No laboratory or vital sign observations are recorded.", [], "missing"))
            return s
        for name in sorted(obs["display"].unique()):
            df = analytics.series(obs, name)
            if df.empty:
                continue
            units = df["unit"].dropna().unique()
            u = f" {units[0]}" if len(units) == 1 else ""
            head = f"{name}{f' ({units[0]})' if len(units) == 1 else ''}: recorded on {dates_phrase(list(df['effective_date']))} ({len(df)} measurement{'s' if len(df) != 1 else ''})."
            parts = [head]
            if len(df) >= 3:
                f_, l_ = df.iloc[0], df.iloc[-1]
                parts.append(f"First recorded value {fmt_num(f_['value_num'])}{u}, latest {fmt_num(l_['value_num'])}{u}.")
                hi, lo = df.loc[df["value_num"].idxmax()], df.loc[df["value_num"].idxmin()]
                parts.append(f"Highest {fmt_num(hi['value_num'])}{u} ({fmt_date(hi['effective_date'])}), lowest {fmt_num(lo['value_num'])}{u} ({fmt_date(lo['effective_date'])}).")
                prev = df.iloc[-2]["value_num"]
                direction = "higher than" if l_["value_num"] > prev else "lower than" if l_["value_num"] < prev else "the same as"
                parts.append(f"The latest value is {direction} the previous recorded value ({fmt_num(prev)}{u}).")
            elif len(df) == 2:
                parts.append(f"Values: {fmt_num(df.iloc[0]['value_num'])}{u} then {fmt_num(df.iloc[1]['value_num'])}{u}. Too few measurements to describe a trend.")
            else:
                parts.append(f"Value: {fmt_num(df.iloc[0]['value_num'])}{u}. Too few measurements to describe a trend.")
            if len(units) > 1:
                parts.append("Recorded in more than one unit (" + ", ".join(units) + "); values have not been converted.")
            flagged = df[df["flag"].notna()]
            if len(flagged):
                parts.append(f"The source system attached a flag to {len(flagged)} of {len(df)} values ({', '.join(sorted(flagged['flag'].unique()))}); flags are reproduced from the source, not calculated here.")
            rr = df[["ref_low", "ref_high"]].drop_duplicates().dropna(how="all")
            if len(rr) == 1:
                parts.append(f"Source reference range: {ref_range_str(df.dropna(subset=['ref_low', 'ref_high'], how='all').iloc[0])}.")
            elif len(rr) == 0:
                parts.append("No reference range is recorded in the source.")
            s.statements.append(Statement(" ".join(parts), list(df["observation_id"])))
        gaps = obs[obs["value_num"].isna() | obs["effective_date"].isna()]
        if len(gaps):
            s.statements.append(Statement(f"{len(gaps)} observation record(s) have no numeric value or no date and are not described above.", list(gaps["observation_id"]), "missing"))
        return s

    # 7
    def _procedures(self, b) -> Section:
        s = Section("procedures", "7. Procedures and interventions")
        p = b["procedures"].sort_values("performed_date", na_position="last")
        if p.empty:
            s.statements.append(Statement("No procedures are recorded.", [], "missing"))
        for _, r in p.iterrows():
            txt = f"{r['display']}: {fmt_date(r['performed_date'])} (status '{r['status']}')."
            if not is_missing(r["note"]):
                txt += f" Note: {r['note']}"
            src = [r["procedure_id"]] + ([r["source_doc_id"]] if not is_missing(r["source_doc_id"]) else [])
            s.statements.append(Statement(txt, src, "fact"))
        return s

    # 8
    def _recent(self, records, b) -> Section:
        s = Section("recent", "8. Recent clinical events")
        r = records.dropna(subset=["date"])
        if r.empty:
            s.statements.append(Statement("No dated events are recorded.", [], "missing"))
            return s
        latest = r["date"].max()
        s.statements.append(Statement(f"Events are listed relative to the most recent dated record ({fmt_date(latest)}), not relative to today.", [], "note"))
        for e in recent_events(records, 6):
            s.statements.append(Statement(f"{fmt_date(e['date'])} - {e['category']}: {e['text']}.", e["keys"]))
        return s

    # 9
    def _followup(self, b, as_of) -> Section:
        s = Section("followup", "9. Documented follow-up plans")
        t = b["tasks"]
        s.statements.append(Statement("This engine reads structured task records only. Plans written in free text inside notes or discharge summaries are not extracted; check the linked documents.", [], "note"))
        if t.empty:
            s.statements.append(Statement("No follow-up tasks are recorded.", [], "missing"))
            return s
        for _, r in t.iterrows():
            src = [r["task_id"]] + ([r["source_doc_id"]] if not is_missing(r["source_doc_id"]) else [])
            status = r["status"] if not is_missing(r["status"]) else None
            due = fmt_date(r["due_date"]) if not is_missing(r["due_date"]) else None
            txt = f"{r['description']} ({r['task_type']}); documented {fmt_date(r['documented_date'])}; "
            txt += f"status '{status}'" if status else "status not recorded"
            txt += f"; due {due}." if due else "; due date not recorded."
            if status == "open" and not is_missing(r["due_date"]) and pd.to_datetime(r["due_date"]).date() < as_of:
                txt += " The due date has passed and no completion is documented in the available records."
            s.statements.append(Statement(txt, src, "fact" if status and due else "missing"))
        return s

    # 10
    def _missing(self, b, findings) -> Section:
        s = Section("missing", "10. Missing or incomplete information")
        if findings.empty:
            s.statements.append(Statement("The implemented documentation checks found no gaps. This does not confirm that the record is complete.", []))
        for check, grp in findings.groupby("check"):
            ids = []
            for rid in grp["record_id"]:
                ids += [x.strip() for x in str(rid).split(",")]
            example = "; ".join(grp["message"].head(3))
            more = f" (+{len(grp) - 3} more)" if len(grp) > 3 else ""
            s.statements.append(Statement(f"{check}: {len(grp)} finding(s). {example}{more}", ids, "missing"))
        for tbl, label in (("procedures", "procedures"), ("tasks", "follow-up tasks"), ("conditions", "conditions")):
            if b[tbl].empty:
                s.statements.append(Statement(f"No {label} are recorded.", [], "missing"))
        s.statements.append(Statement("Absence of a record in CareFlow does not mean the event did not happen; it may be held in a system not available here.", [], "note"))
        return s


# ---- UI -------------------------------------------------------------------------------------------
def render(patient: dict, bundle: dict) -> None:
    from modules.timeline import render_record_detail
    ui.page_header("Clinical Summary", "A structured description of what is documented. It does not replace the original records.")
    ui.synthetic_banner()
    summary = RuleBasedSummaryEngine().generate(bundle)
    records = build_records(bundle).set_index("key")
    st.markdown(ui.badge("generated") + f" Generated by the {summary.engine}. No AI model is connected; nothing leaves this computer. "
                "Every statement lists the records it was built from.", unsafe_allow_html=True)
    ui.draft_banner()
    st.download_button("Download summary (.txt)", summary.to_text(), file_name=f"careflow_summary_{patient['patient_id']}.txt", mime="text/plain")

    for sec in summary.sections:
        with st.container(border=True):
            st.markdown(f"#### {sec.title}")
            for i, stt in enumerate(sec.statements):
                c1, c2 = st.columns([6, 1])
                badge = ""
                if stt.kind == "missing":
                    badge = ui.badge("missing", "NOT RECORDED / INCOMPLETE") + " "
                elif stt.kind == "note":
                    badge = ui.badge("derived", "NOTE") + " "
                c1.markdown(badge + ui.esc(stt.text) if badge else ui.esc(stt.text), unsafe_allow_html=True)
                if stt.sources:
                    with c2.popover(f"Sources ({len(stt.sources)})"):
                        rows = []
                        for k in stt.sources:
                            if k in records.index:
                                rr = records.loc[k]
                                rows.append({"Record": k, "Date": fmt_date(rr["date"]) if not pd.isna(rr["date"]) else "not recorded",
                                             "Category": rr["category"], "Title": rr["title"], "Source": rr["source"]})
                            else:
                                rows.append({"Record": k, "Date": "", "Category": "patient profile", "Title": "", "Source": ""})
                        st.dataframe(pd.DataFrame(rows), hide_index=True, width="stretch")
                else:
                    c2.caption("Derived")
            ids = sec.source_ids
            if ids:
                with st.expander(f"Inspect source records for this section ({len(ids)})"):
                    pick = st.selectbox("Record", ids, key=f"sum_pick_{patient['patient_id']}_{sec.key}",
                                        format_func=lambda k: f"{k} · {records.loc[k, 'title']}" if k in records.index else k)
                    render_record_detail(pick, bundle)
